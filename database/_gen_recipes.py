def R(
    id_, category_id, name, slug, emoji, desc, instr, prep, cook, servings,
    diff, cost, veg, ings,
):
    lines = [
        "    {",
        f'        "id": {id_},',
        f'        "category_id": {category_id},',
        f'        "name": "{name}",',
        f'        "slug": "{slug}",',
        f'        "emoji": "{emoji}",',
        f'        "description": "{desc}",',
        '        "instructions": (',
    ]
    for part in instr.split("\n"):
        escaped = part.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'            "{escaped}\\n"')
    lines.append('        ),')
    lines.append(f'        "prep_time": {prep},')
    lines.append(f'        "cook_time": {cook},')
    lines.append(f'        "servings": {servings},')
    lines.append(f'        "difficulty": "{diff}",')
    lines.append(f'        "cost_level": "{cost}",')
    lines.append(f'        "is_vegetarian": {veg},')
    seen_ids: set[int] = set()
    unique_ings = []
    for ing in ings:
        if ing["id"] in seen_ids:
            continue
        seen_ids.add(ing["id"])
        unique_ings.append(ing)
    ings = unique_ings
    lines.append('        "ingredients": [')
    for ing in ings:
        req = "True" if ing.get("req", True) else "False"
        opt = "True" if ing.get("opt") else "False"
        if ing.get("opt"):
            lines.append(
                f'            _ing({ing["id"]}, "{ing["a"]}", "{ing["u"]}", {ing["i"]}, **_OPT),'
            )
        else:
            lines.append(
                f'            _ing({ing["id"]}, "{ing["a"]}", "{ing["u"]}", {ing["i"]}),'
            )
    lines.append("        ],")
    lines.append("    },")
    return "\n".join(lines)


